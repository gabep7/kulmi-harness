const UNKNOWN_GLYPH = FONT["?"] ?? [0, 0, 0, 0, 0, 0, 0, 0];


export interface RenderedFrame {
  png: Buffer;
  width: number;
  height: number;
}

export interface RenderOptions {
  // Frame width in pixels. Defaults to 1568 (fits OpenAI/Claude image budgets).
  frameWidth?: number;
  // Maximum frames to produce. Defaults to 80.
  maxFrames?: number;
  // Background color [r, g, b]. Defaults to white.
  bg?: [number, number, number];
  // Text color [r, g, b]. Defaults to black.
  fg?: [number, number, number];
}

const DEFAULT_FRAME_WIDTH = 1568;
const DEFAULT_MAX_FRAMES = 80;

// Encode raw RGBA pixels into a PNG buffer.
function encodePng(width: number, height: number, rgba: Uint8Array): Buffer {
  const signature = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

  function chunk(type: string, data: Buffer): Buffer {
    const length = Buffer.alloc(4);
    length.writeUInt32BE(data.length, 0);
    const typeBuf = Buffer.from(type, "ascii");
    const crcInput = Buffer.concat([typeBuf, data]);
    const crc = Buffer.alloc(4);
    crc.writeUInt32BE(crc32(crcInput), 0);
    return Buffer.concat([length, typeBuf, data, crc]);
  }

  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8;
  ihdr[9] = 6;
  ihdr[10] = 0;
  ihdr[11] = 0;
  ihdr[12] = 0;

  // Add filter byte (0 = none) per scanline
  const stride = width * 4;
  const filtered = Buffer.alloc((stride + 1) * height);
  for (let y = 0; y < height; y++) {
    filtered[y * (stride + 1)] = 0;
    rgba.subarray(y * stride, (y + 1) * stride).forEach((b, i) => {
      filtered[y * (stride + 1) + 1 + i] = b;
    });
  }
  const compressed = deflateSync(filtered, { level: 9 });

  return Buffer.concat([
    signature,
    chunk("IHDR", ihdr),
    chunk("IDAT", compressed),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

const CRC_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) {
      c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    }
    table[n] = c >>> 0;
  }
  return table;
})();

function crc32(buf: Buffer): number {
  let crc = 0xffffffff;
  for (let i = 0; i < buf.length; i++) {
    crc = (CRC_TABLE[(crc ^ (buf[i] ?? 0)) & 0xff] ?? 0) ^ (crc >>> 8);
  }
  return (crc ^ 0xffffffff) >>> 0;
}

// Wrap text into lines that fit within the frame width.
function wrapLines(text: string, frameWidth: number): string[] {
  const maxChars = Math.floor((frameWidth - 8) / CHAR_ADVANCE);
  const lines: string[] = [];
  for (const rawLine of text.split("\n")) {
    if (rawLine.length <= maxChars) {
      lines.push(rawLine);
      continue;
    }
    // Break long lines at word boundaries
    let start = 0;
    while (start < rawLine.length) {
      let end = Math.min(start + maxChars, rawLine.length);
      if (end < rawLine.length) {
        const lastSpace = rawLine.lastIndexOf(" ", end);
        if (lastSpace > start) end = lastSpace;
      }
      lines.push(rawLine.slice(start, end));
      start = end;
      while (start < rawLine.length && rawLine[start] === " ") start += 1;
    }
  }
  return lines;
}

export function renderTextToFrames(text: string, options: RenderOptions = {}): RenderedFrame[] {
  const frameWidth = options.frameWidth ?? DEFAULT_FRAME_WIDTH;
  const maxFrames = options.maxFrames ?? DEFAULT_MAX_FRAMES;
  const bg = options.bg ?? [255, 255, 255];
  const fg = options.fg ?? [0, 0, 0];
  const maxRowsPerFrame = Math.floor(4096 / LINE_HEIGHT);

  const lines = wrapLines(text, frameWidth);
  const frames: RenderedFrame[] = [];

  for (let frameStart = 0; frameStart < lines.length; frameStart += maxRowsPerFrame) {
    if (frames.length >= maxFrames) break;
    const frameLines = lines.slice(frameStart, frameStart + maxRowsPerFrame);
    const height = Math.max(LINE_HEIGHT, frameLines.length * LINE_HEIGHT + 4);
    const rgba = new Uint8Array(frameWidth * height * 4);

    // Fill background
    for (let i = 0; i < rgba.length; i += 4) {
      rgba[i] = bg[0];
      rgba[i + 1] = bg[1];
      rgba[i + 2] = bg[2];
      rgba[i + 3] = 255;
    }

    // Draw text
    for (let lineIdx = 0; lineIdx < frameLines.length; lineIdx++) {
      const line = frameLines[lineIdx];
      if (!line) continue;
      const y0 = 2 + lineIdx * LINE_HEIGHT;
      for (let charIdx = 0; charIdx < line.length; charIdx++) {
        const ch = line[charIdx];
        if (!ch) continue;
        const glyph = FONT[ch] ?? UNKNOWN_GLYPH;
        const x0 = 4 + charIdx * CHAR_ADVANCE;
        for (let row = 0; row < glyph.length; row++) {
          const bits = glyph[row];
          if (!bits) continue;
          for (let col = 0; col < GLYPH_W; col++) {
            if (bits & (0x20 >> col)) {
              const px = x0 + col;
              const py = y0 + row;
              if (px < frameWidth && py < height) {
                const offset = (py * frameWidth + px) * 4;
                rgba[offset] = fg[0];
                rgba[offset + 1] = fg[1];
                rgba[offset + 2] = fg[2];
                rgba[offset + 3] = 255;
              }
            }
          }
        }
      }
    }

    frames.push({ png: encodePng(frameWidth, height, rgba), width: frameWidth, height });
  }

  return frames;
}

// Serialize a conversation into dense text for imaging.
// Truncates tool results, caps tool call args, dims tool noise.
export function serializeForImaging(messages: unknown[]): string {
  const parts: string[] = [];
  for (const msg of messages) {
    const m = msg as Record<string, unknown>;
    const role = String(m.role ?? "?");
    if (role === "system") continue;
    let content = "";
    if (typeof m.content === "string") {
      content = m.content;
    } else if (m.content === null) {
      content = "";
    } else if (Array.isArray(m.content)) {
      content = m.content.map((p: unknown) => String((p as Record<string, unknown>)?.text ?? "")).join("");
    }
    // Truncate tool results to head+tail
    if (role === "tool") {
      const bytes = Buffer.byteLength(content, "utf8");
      if (bytes > 2_000) {
        const encoded = Buffer.from(content, "utf8");
        content = `${encoded.subarray(0, 1_200).toString("utf8")}\n[...truncated ${bytes} bytes...]\n${encoded.subarray(Math.max(0, encoded.length - 600)).toString("utf8")}`;
      }
    }
    if (role === "assistant" && Array.isArray(m.tool_calls)) {
      const calls = m.tool_calls as Array<Record<string, unknown>>;
      const callSummary = calls.map((c) => {
        const fn = c.function as Record<string, unknown> | undefined;
        return `${String(fn?.name ?? "?")}(${truncateArgs(String(fn?.arguments ?? ""))})`;
      }).join(", ");
      parts.push(`A: ${content || callSummary}`);
    } else if (role === "tool") {
      parts.push(`  T: ${content}`);
    } else if (role === "user") {
      parts.push(`U: ${content}`);
    } else {
      parts.push(`${role[0]?.toUpperCase() ?? "?"}: ${content}`);
    }
  }
  return parts.join("\n");
}

function truncateArgs(args: string): string {
  if (args.length <= 200) return args;
  return `${args.slice(0, 150)}...(${args.length} chars)`;
}